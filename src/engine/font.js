export const GLYPH_H = 7;
export const LINE_GAP = 3;          // 7 + 3 = a 10px line, like the SNES box font
export const SPACE_ADV = 4;
export const TRACKING = 1;

// Precompute each glyph as a list of lit pixels plus its advance.
const COMPILED = {};
for (const [ch, rows] of Object.entries(G)) {
  const pts = [];
  let right = -1;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') { pts.push([x, y]); if (x > right) right = x; }
    }
  });
  COMPILED[ch] = { pts, adv: (ch === ' ' ? SPACE_ADV : right + 1 + TRACKING) };
}

const FALLBACK = COMPILED['?'];

export function glyph(ch) { return COMPILED[ch] ?? FALLBACK; }

export function charAdvance(ch, scale = 1) { return glyph(ch).adv * scale; }

export function measure(str, scale = 1) {
  let w = 0;
  for (const ch of String(str)) w += glyph(ch).adv;
  return Math.max(0, w * scale - TRACKING * scale);
}

/**
 * Draw a string of bitmap glyphs. `shadow` paints a hard offset copy first,
 * which is the single detail that makes SNES menu text readable over artwork.
 */
export function drawText(ctx, str, x, y, color, { scale = 1, shadow = null } = {}) {
  x = Math.round(x); y = Math.round(y);
  let cx = x;
  const s = scale;
  for (const ch of String(str)) {
    const g = glyph(ch);
    if (g.pts.length) {
      if (shadow) {
        ctx.fillStyle = shadow;
        for (const [gx, gy] of g.pts) ctx.fillRect(cx + gx * s + s, y + gy * s + s, s, s);
      }
      ctx.fillStyle = color;
      for (const [gx, gy] of g.pts) ctx.fillRect(cx + gx * s, y + gy * s, s, s);
    }
    cx += g.adv * s;
  }
  return cx - x;
}

/** Break `str` into lines that fit `maxW` pixels at `scale`. */
export function wrap(str, maxW, scale = 1) {
  const words = String(str).split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const w of words) {
    const test = line ? `${line} ${w}` : w;
    if (measure(test, scale) <= maxW || !line) line = test;
    else { lines.push(line); line = w; }
  }
  if (line) lines.push(line);
  return lines;
}
