// "depths_<n>" ids are never authored above — they're generated on first
// request and cached here so a floor's layout holds still for as long as
// it's reachable, exactly like every hand-authored map. resetDungeonFloors()
// (called only when stepping from depths_entrance into a fresh dive — see
// field.js's "regenDungeon" warp handling) clears the cache so the next
// Floor 1 is never the last dive's.
const DEPTHS_RE = /^depths_(\d+)$/;

export function resetDungeonFloors() {
  for (const key of Object.keys(MAPS)) if (DEPTHS_RE.test(key)) delete MAPS[key];
}

export function getMap(id) {
  let m = MAPS[id];
  if (!m) {
    const depthMatch = DEPTHS_RE.exec(id);
    if (depthMatch) { m = generateDungeonFloor(Number(depthMatch[1])); MAPS[id] = m; }
  }
  if (!m) throw new Error(`unknown map: ${id}`);
  return m;
}

export function tileAt(map, x, y) {
  if (y < 0 || y >= map.tiles.length) return null;
  const row = map.tiles[y];
  if (x < 0 || x >= row.length) return null;
  return LEGEND[row[x]] ?? LEGEND['.'];
}

export function isSolid(map, x, y) {
  const t = tileAt(map, x, y);
  return !t || t.solid;
}

export function mapSize(map) {
  return { w: map.tiles[0].length, h: map.tiles.length };
}

export function warpAt(map, x, y) {
  return (map.warps ?? []).find((wp) => wp.x === x && wp.y === y) ?? null;
}

export function npcAt(map, x, y) {
  return (map.npcs ?? []).find((n) => n.x === x && n.y === y) ?? null;
}

export function chestAt(map, x, y) {
  return (map.chests ?? []).find((c) => c.x === x && c.y === y) ?? null;
}

export function signAt(map, x, y) {
  return (map.signs ?? []).find((s) => s.x === x && s.y === y) ?? null;
}

// Every named region a player can actually travel to, in the order the
// overworld's own warps list them (roughly the order a player encounters
// them) — 'hollowbetween' is appended on its own since it's the one region
// reached through a sub-warp (from the Choir Ruins) rather than directly
// off the world map, but is just as worth surfacing on a world overview.
export const REGIONS = [...MAPS.world.warps.map((w) => w.to), 'hollowbetween'];

// Where the overworld itself drops you when you warp into a region — the
// same landing point a Cartographer's fast-travel reuses (see field.js's
// beginFastTravel), so a warped-to town never lands you anywhere its own
// front gate wouldn't.
export const WORLD_ENTRY_BY_MAP = Object.fromEntries(
  MAPS.world.warps.map((w) => [w.to, { tx: w.tx, ty: w.ty }]),
);

// The overworld is one shared map, so it can't carry a single `theme` field
// the way an individual region map can — instead a handful of named patches
// (in overworld tile coordinates, centred roughly on the warp into the
// region they foreshadow) shade the countryside toward that region's biome
// as you approach it, well before the warp itself. Anything outside every
// patch stays the default green countryside.
const WORLD_THEME_ZONES = [
  { theme: 'ash', cx: 54, cy: 12, r: 12 },      // Ashfall / Cinderreach
  { theme: 'ash', cx: 15, cy: 12, r: 7 },       // Ashquarry, by the Anvil Gorge
  { theme: 'autumn', cx: 36, cy: 47, r: 13 },   // Harrow's Rest / Duskwell
  { theme: 'crystal', cx: 64, cy: 45, r: 12 },  // Glasshaven / the Glassfields
  { theme: 'swamp', cx: 16, cy: 44, r: 12 },    // Tidewatch / the Drowned Vale
];

/** The terrain theme for one overworld cell, or a map's own fixed `theme`
 *  (or 'green') for anywhere else. `x`/`y` are tile coordinates. */
export function themeAt(map, x, y) {
  if (map.id === 'world') {
    for (const z of WORLD_THEME_ZONES) {
      if (Math.hypot(x - z.cx, y - z.cy) < z.r) return z.theme;
    }
    return 'green';
  }
  return map.theme ?? 'green';
}

export const BOSS_SLOTS = ['boss', 'boss2', 'boss3', 'boss4'];

export function bossAt(map, x, y) {
  for (const key of BOSS_SLOTS) {
    const b = map[key];
    if (b && b.x === x && b.y === y) return b;
  }
  return null;
}
